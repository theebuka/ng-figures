// Turns the geoBoundaries Nigeria ADM1 GeoJSON into compact SVG paths.
// Usage: node scripts/build-map.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const src = resolve(root, 'data-src/geoboundaries/nga-adm1.geojson')
const out = resolve(root, 'src/art/map-data.ts')

const WIDTH = 1000
const MIN_STEP = 1.4 // px between kept points
const MIN_RING_AREA = 6 // px², drops specks and tiny islands

// Regions as they stood at independence in 1960, mapped onto today's states.
const REGION_1960 = {
  north: ['Sokoto', 'Kebbi', 'Zamfara', 'Katsina', 'Kano', 'Jigawa', 'Yobe', 'Borno', 'Bauchi', 'Gombe', 'Adamawa', 'Taraba', 'Plateau', 'Nasarawa', 'Benue', 'Kogi', 'Kwara', 'Niger', 'Kaduna', 'Abuja Federal Capital Territory'],
  west: ['Oyo', 'Ogun', 'Ondo', 'Osun', 'Ekiti', 'Edo', 'Delta'],
  east: ['Anambra', 'Enugu', 'Ebonyi', 'Imo', 'Abia', 'Rivers', 'Bayelsa', 'Cross River', 'Akwa Ibom'],
  lagos: ['Lagos'],
}
const regionOf = (name) => Object.keys(REGION_1960).find((r) => REGION_1960[r].includes(name))

const mercY = (lat) => Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360))

const geo = JSON.parse(readFileSync(src, 'utf8'))
const polygonsOf = (g) => (g.type === 'Polygon' ? [g.coordinates] : g.coordinates)

let minLon = Infinity, maxLon = -Infinity, minY = Infinity, maxY = -Infinity
for (const f of geo.features)
  for (const poly of polygonsOf(f.geometry))
    for (const ring of poly)
      for (const [lon, lat] of ring) {
        const y = mercY(lat)
        if (lon < minLon) minLon = lon
        if (lon > maxLon) maxLon = lon
        if (y < minY) minY = y
        if (y > maxY) maxY = y
      }

const lonSpan = maxLon - minLon
const scale = WIDTH / lonSpan
const yScale = scale * (180 / Math.PI)
const HEIGHT = Math.ceil((maxY - minY) * yScale)
const project = ([lon, lat]) => [(lon - minLon) * scale, (maxY - mercY(lat)) * yScale]

const ringArea = (pts) => {
  let a = 0
  for (let i = 0; i < pts.length; i++) {
    const [x1, y1] = pts[i]
    const [x2, y2] = pts[(i + 1) % pts.length]
    a += x1 * y2 - x2 * y1
  }
  return a / 2
}

const thin = (pts) => {
  const kept = [pts[0]]
  for (const p of pts) {
    const [lx, ly] = kept[kept.length - 1]
    if (Math.hypot(p[0] - lx, p[1] - ly) >= MIN_STEP) kept.push(p)
  }
  return kept
}

const r1 = (n) => Math.round(n * 10) / 10

const states = geo.features.map((f) => {
  const name = f.properties.shapeName
  let d = ''
  let best = { area: 0, cx: 0, cy: 0 }
  for (const poly of polygonsOf(f.geometry)) {
    const outer = thin(poly[0].map(project))
    const area = Math.abs(ringArea(outer))
    if (outer.length < 4 || area < MIN_RING_AREA) continue
    d += 'M' + outer.map(([x, y]) => `${r1(x)} ${r1(y)}`).join('L') + 'Z'
    if (area > best.area) {
      const cx = outer.reduce((s, p) => s + p[0], 0) / outer.length
      const cy = outer.reduce((s, p) => s + p[1], 0) / outer.length
      best = { area, cx, cy }
    }
  }
  return {
    id: f.properties.shapeISO.replace('NG-', '').toLowerCase(),
    name: name === 'Abuja Federal Capital Territory' ? 'FCT Abuja' : name,
    region: regionOf(name),
    cx: r1(best.cx),
    cy: r1(best.cy),
    d,
  }
})

const missing = states.filter((s) => !s.region).map((s) => s.name)
if (missing.length) throw new Error(`No 1960 region for: ${missing.join(', ')}`)
states.sort((a, b) => a.name.localeCompare(b.name))

const file = `// Generated by scripts/build-map.mjs. Do not edit by hand.
// Boundaries: geoBoundaries (GRID3), CC BY 4.0.
export type Region1960 = 'north' | 'west' | 'east' | 'lagos'

export interface MapState {
  id: string
  name: string
  region: Region1960
  cx: number
  cy: number
  d: string
}

export const MAP_WIDTH = ${WIDTH}
export const MAP_HEIGHT = ${HEIGHT}

const MIN_LON = ${minLon}
const MAX_MERC_Y = ${maxY}
const SCALE = ${scale}

/** Longitude/latitude to map coordinates, same projection as the paths. */
export function project(lon: number, lat: number): [number, number] {
  const y = Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360))
  return [(lon - MIN_LON) * SCALE, (MAX_MERC_Y - y) * SCALE * (180 / Math.PI)]
}

export const STATES: MapState[] = ${JSON.stringify(states, null, 0).replace(/\},\{/g, '},\n  {').replace(/^\[/, '[\n  ').replace(/\]$/, ',\n]')}
`
writeFileSync(out, file)
console.log(`${states.length} states, ${WIDTH}x${HEIGHT}, ${(file.length / 1024).toFixed(1)} kB -> ${out}`)
